package canon

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode/utf8"
)

type canonicalCase struct {
	Name          string  `json:"name"`
	Tool          string  `json:"tool"`
	Arguments     string  `json:"arguments"`
	Canonical     *string `json:"canonical"`
	DuplicateKeys bool    `json:"duplicate_keys"`
	Hash          string  `json:"hash"`
}

// conformanceDir is where the cases are: the copy kept in this repository,
// or the directory NIA_CONFORMANCE_DIR names. The server's own checks set it
// to the cases it has just generated, so that a change of the engine is
// tried against this code before the copy here is refreshed.
func conformanceDir() string {
	if dir := os.Getenv("NIA_CONFORMANCE_DIR"); dir != "" {
		return dir
	}
	return filepath.Join("..", "conformance")
}

// loadCases reads the cases generated by the reference engine.
func loadCases(t testing.TB) []canonicalCase {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(conformanceDir(), "canonical.json"))
	if err != nil {
		t.Fatalf("reading the conformance cases: %v", err)
	}
	var file struct {
		Version int             `json:"version"`
		Cases   []canonicalCase `json:"cases"`
	}
	if err := json.Unmarshal(raw, &file); err != nil {
		t.Fatalf("decoding the conformance cases: %v", err)
	}
	if file.Version != 1 {
		t.Fatalf("conformance cases are version %d, this test reads version 1", file.Version)
	}
	if len(file.Cases) < 1200 {
		t.Fatalf("only %d conformance cases: the file looks truncated", len(file.Cases))
	}
	return file.Cases
}

func TestConformance(t *testing.T) {
	for _, c := range loadCases(t) {
		t.Run(c.Name, func(t *testing.T) {
			canonical, ok, err := Canonical(c.Arguments)
			if err != nil {
				t.Fatalf("Canonical(%q): %v", c.Arguments, err)
			}
			switch {
			case c.Canonical == nil && ok:
				t.Errorf("Canonical(%q) = %q, the reference hashes the raw text", c.Arguments, canonical)
			case c.Canonical != nil && !ok:
				t.Errorf("Canonical(%q) is not canonical here, the reference gives %q", c.Arguments, *c.Canonical)
			case c.Canonical != nil && canonical != *c.Canonical:
				t.Errorf("Canonical(%q)\n got  %q\n want %q", c.Arguments, canonical, *c.Canonical)
			}
			hash, err := ArgumentsHash(c.Tool, c.Arguments)
			if err != nil {
				t.Fatalf("ArgumentsHash(%q, %q): %v", c.Tool, c.Arguments, err)
			}
			if hash != c.Hash {
				t.Errorf("ArgumentsHash(%q, %q)\n got  %s\n want %s", c.Tool, c.Arguments, hash, c.Hash)
			}
			repeated, err := HasDuplicateKeys(c.Arguments)
			if err != nil {
				t.Fatalf("HasDuplicateKeys(%q): %v", c.Arguments, err)
			}
			if repeated != c.DuplicateKeys {
				t.Errorf("HasDuplicateKeys(%q) = %v, the reference says %v", c.Arguments, repeated, c.DuplicateKeys)
			}
		})
	}
}

// The canonical form is a fixed point: canonical text is its own canonical form.
func TestCanonicalIsStable(t *testing.T) {
	for _, c := range loadCases(t) {
		if c.Canonical == nil {
			continue
		}
		again, ok, err := Canonical(*c.Canonical)
		if err != nil || !ok || again != *c.Canonical {
			t.Errorf("%s: Canonical(%q) = %q, %v, %v", c.Name, *c.Canonical, again, ok, err)
		}
	}
}

func TestInvalidUTF8IsRefused(t *testing.T) {
	for _, text := range []string{"\xff", "{\"a\":\"\xc3\"}", "\xed\xa0\x80"} {
		if _, _, err := Canonical(text); err != ErrInvalidUTF8 {
			t.Errorf("Canonical(%q): error %v, want ErrInvalidUTF8", text, err)
		}
		if _, err := ArgumentsHash("tool", text); err != ErrInvalidUTF8 {
			t.Errorf("ArgumentsHash(tool, %q): error %v, want ErrInvalidUTF8", text, err)
		}
		if _, err := ArgumentsHash(text, "{}"); err != ErrInvalidUTF8 {
			t.Errorf("ArgumentsHash(%q, {}): error %v, want ErrInvalidUTF8", text, err)
		}
		if _, err := HasDuplicateKeys(text); err != ErrInvalidUTF8 {
			t.Errorf("HasDuplicateKeys(%q): error %v, want ErrInvalidUTF8", text, err)
		}
	}
}

// nesting returns how deep arrays and objects nest in a JSON text.
func nesting(text string) int {
	depth, deepest, inString := 0, 0, false
	for i := 0; i < len(text); i++ {
		switch c := text[i]; {
		case inString && c == '\\':
			i++
		case c == '"':
			inString = !inString
		case inString:
		case c == '{' || c == '[':
			depth++
			deepest = max(deepest, depth)
		case c == '}' || c == ']':
			depth--
		}
	}
	return deepest
}

// The grammar accepted here is checked against the standard library's own
// JSON syntax check: within MaxDepth, a text is canonicalised exactly when
// encoding/json says it is valid JSON.
func agreesWithStandardLibrary(t *testing.T, text string) {
	t.Helper()
	_, ok, err := Canonical(text)
	if err != nil {
		t.Fatalf("Canonical(%q): %v", text, err)
	}
	if text == "" {
		// Empty text reads as null here; it is not JSON.
		return
	}
	valid := json.Valid([]byte(text))
	if valid && nesting(text) > MaxDepth {
		valid = false
	}
	if ok != valid {
		t.Errorf("Canonical(%q) ok = %v, encoding/json.Valid = %v", text, ok, valid)
	}
}

func TestGrammarAgreesWithStandardLibrary(t *testing.T) {
	for _, c := range loadCases(t) {
		agreesWithStandardLibrary(t, c.Arguments)
	}
}

func FuzzCanonical(f *testing.F) {
	for _, c := range loadCases(f) {
		f.Add(c.Arguments)
	}
	f.Fuzz(func(t *testing.T, text string) {
		if !utf8.ValidString(text) {
			if _, _, err := Canonical(text); err != ErrInvalidUTF8 {
				t.Fatalf("Canonical(%q): error %v, want ErrInvalidUTF8", text, err)
			}
			return
		}
		agreesWithStandardLibrary(t, text)
		canonical, ok, _ := Canonical(text)
		if !ok {
			return
		}
		if !json.Valid([]byte(canonical)) {
			t.Fatalf("Canonical(%q) = %q, which is not JSON", text, canonical)
		}
		if strings.ContainsAny(canonical, " \t\r\n") && !strings.Contains(canonical, `"`) {
			t.Fatalf("Canonical(%q) = %q keeps whitespace outside a string", text, canonical)
		}
		again, ok, _ := Canonical(canonical)
		if !ok || again != canonical {
			t.Fatalf("not a fixed point: Canonical(%q) = %q, then %q", text, canonical, again)
		}
		if _, err := HasDuplicateKeys(text); err != nil {
			t.Fatalf("HasDuplicateKeys(%q): %v", text, err)
		}
	})
}
