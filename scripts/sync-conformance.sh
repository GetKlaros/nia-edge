#!/usr/bin/env bash
# Refreshes conformance/*.json from the cases the Nia server generated.
#   scripts/sync-conformance.sh /path/to/nia/conformance
set -euo pipefail
cd "$(dirname "$0")/.."
if [ $# -ne 1 ] || [ ! -d "$1" ]; then
  echo "usage: scripts/sync-conformance.sh <directory of the cases generated by the server>" >&2
  exit 2
fi
source_dir=$1
found=0
for file in "$source_dir"/*.json; do
  [ -f "$file" ] || continue
  cp "$file" "conformance/$(basename "$file")"
  found=$((found + 1))
done
[ "$found" -gt 0 ] || { echo "sync-conformance: no .json file in $source_dir" >&2; exit 1; }
# A case file the server no longer generates must not linger here.
for file in conformance/*.json; do
  [ -f "$source_dir/$(basename "$file")" ] || { echo "sync-conformance: $file is no longer generated by the server: remove it" >&2; exit 1; }
done
git status --short conformance
